// Reads environment variables from process.env (Netlify/CI) and .env (local)
// and writes src/environments/environment.ts so Angular can read them
// at build time without a runtime dependency on Node's process.env.

const fs = require('node:fs');
const path = require('node:path');

const rootDir = path.resolve(__dirname, '..');
const envPath = path.join(rootDir, '.env');
const outDir = path.join(rootDir, 'src', 'environments');
const outPath = path.join(outDir, 'environment.ts');

function parseEnvFile(filePath) {
  const values = {};

  if (!fs.existsSync(filePath)) {
    return values;
  }

  const lines = fs.readFileSync(filePath, 'utf8').split(/\r?\n/);

  for (const line of lines) {
    const trimmed = line.trim();

    if (!trimmed || trimmed.startsWith('#')) {
      continue;
    }

    const eqIndex = trimmed.indexOf('=');

    if (eqIndex === -1) {
      continue;
    }

    const key = trimmed.slice(0, eqIndex).trim();
    let value = trimmed.slice(eqIndex + 1).trim();

    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }

    values[key] = value;
  }

  return values;
}

// Read .env for local development.
const env = parseEnvFile(envPath);

// Netlify/CI variables from process.env take priority.
// .env is used as a fallback for local development.
const googleScriptUrl =
  process.env.GOOGLE_SCRIPT_URL || env.GOOGLE_SCRIPT_URL || '';

const rawRsvp =
  process.env.RSVP ?? env.RSVP;

// Default RSVP to true if no value is provided.
let rsvpValue = true;

if (typeof rawRsvp === 'string') {
  const low = rawRsvp.trim().toLowerCase();

  if (
    low === 'false' ||
    low === '0' ||
    low === 'no'
  ) {
    rsvpValue = false;
  } else {
    rsvpValue = true;
  }
}

const content = `// Auto-generated by scripts/generate-environment.js — do not edit directly.

export const environment = {
  GOOGLE_SCRIPT_URL: '${googleScriptUrl.replace(/'/g, "\\'")}',
  RSVP: ${rsvpValue}
};
`;

fs.mkdirSync(outDir, { recursive: true });

fs.writeFileSync(outPath, content, 'utf8');

console.log(`Generated ${path.relative(rootDir, outPath)}`);
console.log(`GOOGLE_SCRIPT_URL: ${googleScriptUrl ? 'configured' : 'not configured'}`);
console.log(`RSVP: ${rsvpValue}`);
